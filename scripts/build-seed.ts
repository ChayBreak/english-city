// Writes supabase/seed.sql from src/data/seed.ts.
// Run with `npm run seed:sql` (Node 22.18+ strips the TypeScript types itself).
import { writeFileSync } from "node:fs";
import { seedCourses, seedPaymentSettings, seedPlans } from "../src/data/seed.ts";

const value = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "object") return `${value(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replaceAll("'", "''")}'`;
};

const insert = (table: string, row: Record<string, unknown>) => {
  const keys = Object.keys(row);
  return `insert into public.${table} (${keys.join(", ")}) values (${keys
    .map((key) => value(row[key]))
    .join(", ")}) on conflict do nothing;`;
};

const lines = [
  "-- Generated by scripts/build-seed.ts from src/data/seed.ts. Run once after the migration.",
  "begin;",
  ...seedPlans.map((plan) => insert("plans", plan)),
  `update public.payment_settings set ${Object.entries(seedPaymentSettings)
    .map(([key, v]) => `${key} = ${value(v)}`)
    .join(", ")} where id = 1;`,
];

for (const { lessons, ...course } of seedCourses) {
  lines.push("", `-- ${course.title} · ${course.level}`, insert("courses", course));
  for (const { materials, tasks, ...lesson } of lessons) {
    lines.push(insert("lessons", lesson), insert("lesson_materials", materials));
    for (const task of tasks) lines.push(insert("tasks", task));
  }
}
lines.push("commit;", "");

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), lines.join("\n"));
console.log("supabase/seed.sql written");
